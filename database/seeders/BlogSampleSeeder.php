اگر آرزویی داری که با توان خودت دور از دسترس است، **ثبت آرزو در آرزو** ساده‌ترین راه برای دیده‌شدن آن است. در این راهنما قدم‌به‌قدم یاد می‌گیری چطور آرزویت را درست ثبت کنی، چه مدارکی لازم است و بعد از ثبت چه اتفاقی می‌افتد.

## آرزو چه آرزوهایی را می‌پذیرد؟

در آرزو می‌توانی آرزوهایی را در این دسته‌ها ثبت کنی: **تحصیلی** (لپ‌تاپ، کتاب، شهریه)، **درمانی** (دارو و تجهیزات پزشکی)، **وسایل ضروری**، **آموزشی** (کلاس و مهارت‌آموزی)، **تجربه و تفریح**، **خانواده** و **سایر**. هر آرزو قبل از انتشار توسط تیم آرزو بررسی می‌شود تا فقط درخواست‌های واقعی و روشن در سایت نمایش داده شوند.

## پیش از شروع: چه چیزهایی آماده کنیم؟

قبل از ثبت آرزو این موارد را آماده کن تا کار در چند دقیقه تمام شود:

- **حساب کاربری:** با شماره موبایل [ثبت‌نام](/register) کن یا وارد حسابت شو.
- **عنوان کوتاه و روشن** برای آرزو، مثلاً «لپ‌تاپ برای ادامه تحصیل».
- **مبلغ تقریبی** مورد نیاز به تومان.
- **یک عکس مرتبط** با آرزو (اختیاری، حداکثر ۳ مگابایت).
- **مدرک هویتی و مدرک تأییدکننده** (برای بررسی تیم آرزو؛ این مدارک خصوصی می‌مانند و در سایت نمایش داده نمی‌شوند).

## مرحله به مرحله: ثبت آرزو

![چهار مرحله ثبت آرزو](__API__/images/blog/how-to-register-wish-steps.svg)

### مرحله ۱: عنوان و دسته‌بندی

به صفحه [ثبت آرزو](/create-wish) برو. یک **عنوان کوتاه** (حداکثر ۱۸۰ کاراکتر) بنویس و دسته‌بندی مناسب را انتخاب کن. عنوان خوب مشخص است: به‌جای «کمک می‌خواهم»، بنویس «لپ‌تاپ برای دانشجوی مهندسی».

### مرحله ۲: توضیح کوتاه و داستان آرزو

در **توضیح کوتاه** در یک یا دو جمله بگو آرزویت چیست. در **داستان آرزو** صادقانه و محترمانه توضیح بده چرا این آرزو برایت مهم است و برآورده شدنش چه تغییری ایجاد می‌کند. داستان واقعی و دقیق، شانس تأیید و دیده‌شدن را بالا می‌برد.

### مرحله ۳: شهر و مبلغ

شهر محل زندگی‌ات را انتخاب کن و مبلغ تقریبی آرزو را به تومان وارد کن. مبلغ را واقع‌بینانه بنویس و در صورت امکان بر اساس قیمت واقعی بازار. همچنین می‌توانی فوریت آرزو را (عادی، مهم یا فوری) مشخص کنی؛ آرزوهای مهم و فوری بعد از تأیید در بخش ویژه صفحه اصلی نمایش داده می‌شوند.

### مرحله ۴: اطلاعات متقاضی و مدارک

نام و شماره موبایل متقاضی و نسبت او با آرزو (خودم، عضو خانواده یا شخص دیگری با اطلاع او) را وارد کن و مدارک را بارگذاری کن. **اطلاعات تماس و مدارک تو خصوصی می‌ماند** و فقط برای بررسی در اختیار تیم آرزو قرار می‌گیرد.

## بعد از ثبت چه اتفاقی می‌افتد؟

بعد از ارسال، آرزو در وضعیت **«در انتظار بررسی»** قرار می‌گیرد و شماره پیگیری دریافت می‌کنی. تیم آرزو درخواست را بررسی می‌کند و نتیجه یکی از این‌هاست:

1. **تأیید شده:** آرزو در بخش [آرزوها](/wishes) منتشر می‌شود و دیگران آن را می‌بینند.
2. **نیازمند اطلاعات بیشتر:** از تو خواسته می‌شود اطلاعات یا مدرک تکمیلی ارسال کنی.
3. **رد شده:** دلیل رد در پیام بررسی نوشته می‌شود تا بتوانی آن را اصلاح و دوباره ثبت کنی.

نتیجه بررسی در بخش **اعلان‌ها** در [داشبورد](/dashboard/notifications) هم برایت ثبت می‌شود و وضعیت همه آرزوهایت را از «آرزوهای من» می‌توانی دنبال کنی.

## ۷ نکته برای ثبت یک آرزوی قابل‌اعتماد

- عنوان را **دقیق و کوتاه** بنویس.
- **داستان واقعی** و بدون اغراق بگو.
- مبلغ را بر اساس **قیمت واقعی** تعیین کن.
- از **عکس واضح** و مرتبط استفاده کن.
- مدارک را **خوانا** و کامل بارگذاری کن.
- شماره موبایلی بنویس که **همیشه در دسترس** است.
- اطلاعات شخصی غیرضروری (مثل شماره کارت) را در متن آرزو ننویس.

